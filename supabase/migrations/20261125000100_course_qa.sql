BEGIN;
CREATE TABLE IF NOT EXISTS public.course_questions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL REFERENCES public.students(id),
    course_code text NOT NULL CHECK (course_code ~ '^[A-Z]{2,4} [0-9]{3}[A-Z]?$'),
    title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 160),
    body text NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 4000),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.course_answers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id bigint NOT NULL REFERENCES public.course_questions(id) ON DELETE CASCADE,
    author_id bigint NOT NULL REFERENCES public.students(id),
    body text NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 4000),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (question_id, id)
);
CREATE TABLE IF NOT EXISTS public.course_helpful_answers (
    question_id bigint PRIMARY KEY REFERENCES public.course_questions(id) ON DELETE CASCADE,
    answer_id bigint NOT NULL,
    FOREIGN KEY (question_id, answer_id) REFERENCES public.course_answers(question_id, id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS course_questions_course ON public.course_questions(course_code, id DESC);
CREATE INDEX IF NOT EXISTS course_answers_question ON public.course_answers(question_id, id);
ALTER TABLE public.course_questions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.course_answers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.course_helpful_answers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.course_questions, public.course_answers, public.course_helpful_answers FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.course_questions_id_seq, public.course_answers_id_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.course_questions, public.course_answers, public.course_helpful_answers TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.course_questions_id_seq, public.course_answers_id_seq TO service_role;
NOTIFY pgrst, 'reload schema';
COMMIT;
